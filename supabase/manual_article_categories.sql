-- Run once in Supabase SQL Editor to enable persistent custom article categories.
create table if not exists public.article_categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  slug text not null unique,
  created_at timestamptz not null default now()
);

alter table public.article_categories enable row level security;
revoke all on public.article_categories from anon, authenticated;
grant select, insert, update, delete on public.article_categories to service_role;
grant usage, select on sequence public.article_categories_id_seq to service_role;

